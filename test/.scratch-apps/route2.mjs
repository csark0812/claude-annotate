import { startServer, launch, sleep, until, notesOf } from "./lib.mjs";
const URL0 = process.argv[2], DELAY = Number(process.argv[3] || 200);
const srv = await startServer();
const b = await launch(srv.session);
const p = b.page;
await p.goto(URL0);
await p.waitForSelector("#lazy-panel");
await b.on();
await b.noteOn(p, "#title", "home note");
await sleep(Number(process.argv[4] || 0));
// hold Space, click the router link, let go, mark right away
await p.mouse.move(5, 5);
await p.keyboard.down(" ");
await sleep(100);
await p.click("#to-about");
await p.keyboard.up(" ");
await p.waitForSelector("#about-title");
await sleep(DELAY);
console.log("pins on screen after route change:", await p.evaluate(() => document.querySelector("claude-annotate").shadowRoot.querySelectorAll(".pin").length));
await b.noteOn(p, "#about-text", "about note");
const got = await srv.next(6000);
console.log("second batch:\n" + notesOf(got));
console.log("another batch?:", notesOf(await srv.next(4000)));
const ov = await srv.overview();
console.log("server pages:", JSON.stringify(ov.pages.map((pg) => [pg.url, pg.notes.map((n) => n.text)])));
console.log("state /:", (await srv.state(new URL("/", URL0).href)).notes?.map((n) => n.text), "state /about:", (await srv.state(new URL("/about", URL0).href)).notes?.map((n) => n.text));
await b.close(); await srv.close();
