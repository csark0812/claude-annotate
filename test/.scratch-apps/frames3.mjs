import fs from "node:fs";
import { chromium } from "playwright-core";
import { serve } from "./lab-server.mjs";
const s1 = await serve(5201, "http://127.0.0.1:5202"); const s2 = await serve(5202, "");
const br = await chromium.launch({ channel: "chromium" });
const p = await br.newPage();
await p.goto("http://localhost:5201/lab");
const cf = p.frames().find((f) => f.url().startsWith("http://127.0.0.1:5202"));
const src = fs.readFileSync("server/overlay.js", "utf8").replace("catch { /* answer null */ }", "catch (err) { window.__err = String(err); }");
await cf.evaluate(src);
await p.evaluate(() => document.getElementById("cross").contentWindow.postMessage({ claudeAnnotate: "at", id: "x", x: 11, y: 55 }, "*"));
await new Promise((r) => setTimeout(r, 300));
console.log("error inside the frame probe:", await cf.evaluate(() => window.__err));
await br.close(); s1.close(); s2.close();
